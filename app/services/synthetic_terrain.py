"""确定性合成 DEM fixture（G3D01 D5 —— 纯本地三维地形演示路径）。

目的：为三维地形管线提供**零外部依赖**的本地高程源 —— 无网络、无真实
数据许可、无坐标/基准争议。合成 DEM 经既有 fail-closed 管线（GeoTIFF →
``raster_tile_service.render_terrarium_tile`` → terrain-tiles 路由 →
MapLibre raster-dem）服务，端到端行为与真实会话 DEM 完全一致。

数据诚信红线：
- 治理画像 ``basemap_profiles.ELEVATION_SOURCE_PROFILES`` 中
  ``synthetic-demo-dem`` 的 ``synthetic=True`` 由模型校验强制
  ``qualification="display_only"`` —— 本模块不自设资格，任何科学分析
  入口按 display_only 拒绝；
- 生成的 GeoTIFF 元数据写入 ``SYNTHETIC_DEM=1`` tag 与
  ``image_description``，文件自描述（下游用 rasterio 读到即知是合成数据，
  无法冒充真实高程）；
- 数值特征刻意**不像任何真实地形**（平滑高斯山脊叠加，无水系/粗糙度），
  即使被误用作分析，量级与形态也不具备欺骗性。
"""
from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any, NamedTuple

import numpy as np

from app.lib.cartography.basemap_profiles import get_elevation_profile
from app.services.raster_tile_service import register_raster_ref

SYNTHETIC_DEM_SOURCE_ID = "synthetic-demo-dem"

#: 默认演示窗口：成都市及周边（经纬度，EPSG:4326）。
DEFAULT_DEMO_BBOX = (103.90, 30.50, 104.25, 30.80)
DEFAULT_SHAPE = (512, 512)
DEFAULT_SEED = 42

#: 高程范围（米）——刻意选真实川西平原边缘的量级但形态纯合成。
_MIN_ELEV_M = 400.0
_MAX_ELEV_M = 1600.0

_DEMO_NOTE = (
    "Synthetic demo terrain generated by app/services/synthetic_terrain.py — "
    "NOT real elevation data; display only, never for scientific analysis."
)


class SyntheticTerrainRef(NamedTuple):
    """合成地形 ref 构建结果（供调用方写入 MapSpec / 会话）。"""

    ref_id: str
    raster_path: str
    bbox: tuple[float, float, float, float]
    shape: tuple[int, int]
    seed: int
    content_sha256: str
    qualification: str
    synthetic: bool
    terrain_tiles_url_template: str


def generate_synthetic_elevation(
    shape: tuple[int, int] = DEFAULT_SHAPE,
    seed: int = DEFAULT_SEED,
) -> np.ndarray:
    """确定性合成高程阵列（float32, 米）。

    形态 = 若干高斯山脊/孤峰 + 环形盆地 + 缓坡面，经量级钳制 —— 纯演示
    用地形，与任何真实 DEM 无对应关系。同 seed 在**同一 NumPy 构建**内
    逐位一致（default_rng 的 PCG64 流跨平台确定，但 float64 超越函数
    可能随 SIMD/版本差 1 ULP —— 不承诺跨机构逐字节复现）。
    """
    h, w = shape
    ys, xs = np.mgrid[0:h, 0:w].astype(np.float64)
    nx = xs / max(w - 1, 1)  # 0..1
    ny = ys / max(h - 1, 1)

    elev = np.zeros((h, w), dtype=np.float64)
    # 山脊/孤峰（位置由 seed 派生，参数固定 —— 不引入真实地名对应）
    rng = np.random.default_rng(seed)
    for _ in range(5):
        cx, cy = 0.15 + 0.7 * rng.random(), 0.15 + 0.7 * rng.random()
        sigma = 0.05 + 0.12 * rng.random()
        amp = 300.0 + 500.0 * rng.random()
        elev += amp * np.exp(-(((nx - cx) ** 2) + (ny - cy) ** 2) / (2 * sigma * sigma))
    # 环形盆地（凹陷）
    elev -= 250.0 * np.exp(-(((nx - 0.75) ** 2) + (ny - 0.75) ** 2) / (2 * 0.08**2))
    # 区域缓坡（西高东低 —— 平原向山地过渡的示意）
    elev += 350.0 * (1.0 - nx)
    return np.clip(elev + _MIN_ELEV_M, _MIN_ELEV_M, _MAX_ELEV_M).astype(np.float32)


def write_synthetic_dem(
    path: str | Path,
    bbox: tuple[float, float, float, float] = DEFAULT_DEMO_BBOX,
    shape: tuple[int, int] = DEFAULT_SHAPE,
    seed: int = DEFAULT_SEED,
) -> Path:
    """写合成 DEM GeoTIFF（EPSG:4326 / float32 / nodata=-9999 / 自描述 tag）。

    经既有 ``render_terrarium_tile`` 的全部 fail-closed 检查（单波段、
    CRS、nodata → 透明像素）—— 合成数据与真实会话 DEM 走同一条数据面，
    不建旁路。
    """
    import rasterio
    from rasterio.transform import from_bounds

    elevation = generate_synthetic_elevation(shape=shape, seed=seed)
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    profile = {
        "driver": "GTiff",
        "width": shape[1],
        "height": shape[0],
        "count": 1,
        "dtype": "float32",
        "crs": "EPSG:4326",
        "transform": from_bounds(*bbox, width=shape[1], height=shape[0]),
        "nodata": -9999.0,
    }
    with rasterio.open(out, "w", **profile) as dst:
        dst.write(elevation, 1)
        dst.set_band_description(1, "synthetic_elevation_m (display only)")
        dst.update_tags(SYNTHETIC_DEM="1", SYNTHETIC_SEED=str(seed))
        dst.update_tags(1, SYNTHETIC_DEM="1")
    return out


def synthetic_terrain_qualification() -> dict[str, Any]:
    """合成 DEM 的科学资格判定（typed，绝不静默升级）。

    与 G01/G02 数据资格管线对接时消费本函数：``qualification`` 对齐
    ``basemap_profiles`` 词表；``remediation`` 说明唯一出路是替换为真实
    DEM（不可"校准"合成数据）。
    """
    profile = get_elevation_profile(SYNTHETIC_DEM_SOURCE_ID)
    if profile is None:  # pragma: no cover - 目录契约锁保证存在
        raise LookupError(f"elevation profile '{SYNTHETIC_DEM_SOURCE_ID}' missing")
    return {
        "source_id": profile.source_id,
        "qualification": profile.qualification,
        "synthetic": profile.synthetic,
        "vertical_datum": profile.vertical_datum,
        "reason_code": "SYNTHETIC_DEM_DISPLAY_ONLY",
        "detail": _DEMO_NOTE,
        "remediation": "替换为真实 DEM（会话 raster ref）；合成数据不可校准为分析级",
    }


def build_synthetic_terrain_ref(
    session_id: str,
    ref_id: str,
    dest_dir: str | Path,
    bbox: tuple[float, float, float, float] = DEFAULT_DEMO_BBOX,
    shape: tuple[int, int] = DEFAULT_SHAPE,
    seed: int = DEFAULT_SEED,
) -> SyntheticTerrainRef:
    """生成合成 DEM 并注册为会话 raster ref（terrain-tiles 路由即可服务）。

    调用方拥有 ``dest_dir``（会话上传目录 / 临时目录）；ref 失效走既有
    ``ref_lifecycle``（overwrite/rollback/delete → raster tile 缓存清理）。
    """
    qual = synthetic_terrain_qualification()
    raster_path = write_synthetic_dem(
        Path(dest_dir) / f"{ref_id}.synthetic-dem.tif",
        bbox=bbox,
        shape=shape,
        seed=seed,
    )
    content_sha256 = hashlib.sha256(raster_path.read_bytes()).hexdigest()
    register_raster_ref(session_id, ref_id, str(raster_path))
    return SyntheticTerrainRef(
        ref_id=ref_id,
        raster_path=str(raster_path),
        bbox=bbox,
        shape=shape,
        seed=seed,
        content_sha256=content_sha256,
        qualification=qual["qualification"],
        synthetic=qual["synthetic"],
        terrain_tiles_url_template=(
            f"/api/v1/layers/data/{ref_id}/terrain-tiles/{{z}}/{{x}}/{{y}}.png"
        ),
    )


