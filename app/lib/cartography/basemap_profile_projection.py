"""Basemap/elevation 治理画像 → TypeScript 值投影（G3D01 D2）。

权威目录在 ``app/lib/cartography/basemap_profiles.py``（typed catalog）；
本模块把它**确定性投影**为 ``frontend/lib/basemap-profiles.generated.ts``
（值投影，非类型投影 —— 与 ts_projection 的 schema 投影互补）。前端
``providers.ts`` / renderer / 契约测试消费该生成物，手维护平行目录自此
消除：名字/署名/许可漂移在双侧契约测试即红。

再生成幂等（byte 级，``tests/cartography/test_basemap_profile_projection.py``
锁定）。运行：``python -m app.lib.cartography.basemap_profile_projection``
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

from app.lib.cartography.basemap_profiles import (
    BASEMAP_PROVIDER_PROFILES,
    BASEMAP_PROFILES_VERSION,
    ELEVATION_FALLBACK_ID,
    ELEVATION_SOURCE_PROFILES,
    TERRAIN_CAPABILITY,
)

REPO_ROOT = Path(__file__).resolve().parents[3]
OUTPUT = REPO_ROOT / "frontend" / "lib" / "basemap-profiles.generated.ts"

HEADER = """\
/**
 * AUTO-GENERATED by app/lib/cartography/basemap_profile_projection.py —— DO NOT EDIT.
 *
 * 底图/高程源治理画像的权威目录在
 * app/lib/cartography/basemap_profiles.py（Pydantic typed catalog）；
 * 本文件是其 TypeScript 值投影。修改目录请改权威模块后运行
 * `python -m app.lib.cartography.basemap_profile_projection` 再生成。
 *
 * 契约锁：tests/cartography/test_basemap_profile_projection.py（再生成幂等
 * + 与 frontend providers/base_layers 一致）与
 * frontend/lib/basemap-profiles.contract.test.ts（TILE_PROVIDERS 一致）。
 */
"""

_TYPES = """\
export interface BasemapCachePolicy {
  browserCacheAllowed: boolean;
  serverProxyCacheAllowed: boolean;
  offlineBulkDownload: 'allowed' | 'restricted' | 'forbidden';
  offlineNote?: string;
}

export interface BasemapProviderProfile {
  providerId: string;
  /** 与 TILE_PROVIDERS[].name 严格一致（switch_base_layer 匹配键） */
  name: string;
  kind: 'raster_xyz' | 'vector_style' | 'wmts_rest';
  mapStyleType: 'raster' | 'vector';
  /** URL 模板；``{env:VAR}`` 占位 = 部署期环境变量注入 */
  url: string;
  attribution: string;
  license: string;
  licenseUrl?: string;
  tosUrl?: string;
  maxZoom: number;
  crs: string;
  coverage: string;
  requiresCredentials: boolean;
  /** 环境变量名（绝不内联值） */
  credentialsEnv?: string;
  envGate?: string;
  deployment: 'cloud' | 'cloud+air_gapped' | 'air_gapped_only';
  cachePolicy: BasemapCachePolicy;
  keywords: readonly string[];
  llmVisible: boolean;
  notes?: string;
}

export interface ElevationSourceProfile {
  sourceId: string;
  kind: 'session_ref' | 'remote_terrarium_xyz' | 'synthetic_local';
  encoding: 'terrarium' | 'mapbox';
  maxZoom: number;
  verticalUnit: 'm';
  /** null = 混合源垂直基准不统一（display_only 资格的原因之一） */
  verticalDatum: string | null;
  url: string | null;
  attribution: string;
  /** 导出/打印面应展示的完整署名清单 */
  attributionDetail: string | null;
  license: string;
  licenseUrl: string | null;
  synthetic: boolean;
  qualification: 'analysis_grade' | 'display_only' | 'unavailable' | 'unknown';
  deployment: 'cloud' | 'cloud+air_gapped' | 'air_gapped_only';
  notes: string | null;
}

export interface TerrainCapabilityProfile {
  supportsTerrain: boolean;
  supportedEncodings: readonly string[];
  maxExaggeration: number;
  defaultMaxzoom: number;
  defaultTileSize: number;
  requiresSpecBoundSource: boolean;
  specBinding: string;
}
"""


def _opt(v: Optional[str]) -> Optional[str]:
    return v if v else None


def _basemap_dict(p: Any) -> dict[str, Any]:
    d: dict[str, Any] = {
        "providerId": p.provider_id,
        "name": p.name,
        "kind": p.kind,
        "mapStyleType": p.map_style_type,
        "url": p.url,
        "attribution": p.attribution,
        "license": p.license,
        "maxZoom": p.max_zoom,
        "crs": p.crs,
        "coverage": p.coverage,
        "requiresCredentials": p.requires_credentials,
        "deployment": p.deployment,
        "cachePolicy": {
            "browserCacheAllowed": p.cache_policy.browser_cache_allowed,
            "serverProxyCacheAllowed": p.cache_policy.server_proxy_cache_allowed,
            "offlineBulkDownload": p.cache_policy.offline_bulk_download,
        },
        "keywords": list(p.keywords),
        "llmVisible": p.llm_visible,
    }
    if p.license_url:
        d["licenseUrl"] = p.license_url
    if p.tos_url:
        d["tosUrl"] = p.tos_url
    if p.credentials_env:
        d["credentialsEnv"] = p.credentials_env
    if p.env_gate:
        d["envGate"] = p.env_gate
    if p.cache_policy.offline_note:
        d["cachePolicy"]["offlineNote"] = p.cache_policy.offline_note
    if p.notes:
        d["notes"] = p.notes
    return d


def _elevation_dict(e: Any) -> dict[str, Any]:
    return {
        "sourceId": e.source_id,
        "kind": e.kind,
        "encoding": e.encoding,
        "maxZoom": e.max_zoom,
        "verticalUnit": e.vertical_unit,
        "verticalDatum": e.vertical_datum,
        "url": e.url,
        "attribution": e.attribution,
        "attributionDetail": e.attribution_detail,
        "license": e.license,
        "licenseUrl": e.license_url,
        "synthetic": e.synthetic,
        "qualification": e.qualification,
        "deployment": e.deployment,
        "notes": e.notes,
    }


def _terrain_dict(t: Any) -> dict[str, Any]:
    return {
        "supportsTerrain": t.supports_terrain,
        "supportedEncodings": list(t.supported_encodings),
        "maxExaggeration": t.max_exaggeration,
        "defaultMaxzoom": t.default_maxzoom,
        "defaultTileSize": t.default_tile_size,
        "requiresSpecBoundSource": t.requires_spec_bound_source,
        "specBinding": t.spec_binding,
    }


def _dump(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2)


def render() -> str:
    parts: list[str] = [HEADER, _TYPES]
    parts.append(f"export const BASEMAP_PROFILES_VERSION = {json.dumps(BASEMAP_PROFILES_VERSION)};\n")
    parts.append(
        "export const BASEMAP_PROVIDER_PROFILES: readonly BasemapProviderProfile[] = "
        f"{_dump([_basemap_dict(p) for p in BASEMAP_PROVIDER_PROFILES])};\n"
    )
    parts.append(
        "export const ELEVATION_SOURCE_PROFILES: readonly ElevationSourceProfile[] = "
        f"{_dump([_elevation_dict(e) for e in ELEVATION_SOURCE_PROFILES])};\n"
    )
    parts.append(
        "export const TERRAIN_CAPABILITY: TerrainCapabilityProfile = "
        f"{_dump(_terrain_dict(TERRAIN_CAPABILITY))};\n"
    )
    parts.append(
        "export const ELEVATION_FALLBACK_ID = "
        f"{json.dumps(ELEVATION_FALLBACK_ID)};\n"
    )
    return "\n".join(parts)


def generate() -> Path:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    return OUTPUT


def check_drift() -> dict[str, Any]:
    """契约测试入口：再生成 vs 已提交文件（byte 级幂等）。"""
    if not OUTPUT.exists():
        return {"drifted": True, "path": str(OUTPUT), "reason": "missing"}
    committed = OUTPUT.read_text(encoding="utf-8")
    if committed == render():
        return {"drifted": False, "path": str(OUTPUT), "reason": None}
    return {
        "drifted": True,
        "path": str(OUTPUT),
        "reason": "committed file differs from regeneration",
    }


if __name__ == "__main__":
    out = generate()
    print(f"wrote {out}")
