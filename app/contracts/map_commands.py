"""Map command 清单 —— 前端地图命令通道的唯一权威词表（#535 / PR-A）。

工具结果里的 ``command`` 键（以及 ``commands[]`` 批量项）是**前端地图动作
通道的保留键**：``ToolDispatchService`` 为其铸 ``action_id`` 并经 SSE
``step_result`` 下发，前端 ``map-action-handler`` 在 ``COMMAND_CATALOGUE``
里按小写名查找执行。不在本清单里的名字没有前端执行体，下发只会产生
``unknown_command`` 失败回执（噪声 ACK 证据）——dispatcher 因此只转发
清单内的名字（``is_map_command``）。

工具若需要在结果里自标识，请用 ``tool`` 键，**不要**用 ``command``。

本清单投影为 ``frontend/lib/map-commands/manifest.generated.ts``
（``python -m app.contracts.map_commands`` 再生成，byte 级幂等）：

- 后端契约：``tests/unit/test_map_command_manifest.py``（生成物无漂移 +
  app/ 内全部 ``command`` 字面量 ⊆ 清单 + dispatcher 门禁）；
- 前端契约：``frontend/lib/map-commands/catalogue-contract.test.ts``
  （``COMMAND_CATALOGUE`` 键集 == 清单，双向；字面量扫描 ⊆ 目录）。

新增地图命令：先在此登记，再生成，再在前端目录实现执行体。
"""
