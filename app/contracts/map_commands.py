MAP_COMMAND_SET = frozenset(MAP_COMMANDS)


def is_map_command(name: Any) -> bool:
    """``name`` 是否是前端注册的地图命令（大小写不敏感，与前端查找一致）。"""
    return isinstance(name, str) and name.lower() in MAP_COMMAND_SET


REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "frontend" / "lib" / "map-commands" / "manifest.generated.ts"

_HEADER = """\
/**
 * AUTO-GENERATED by app/contracts/map_commands.py —— DO NOT EDIT.
 *
 * 前端地图命令通道的权威词表（后端导出）。COMMAND_CATALOGUE 的键集必须
 * 与本清单完全相等（catalogue-contract.test.ts 双向锁定）；dispatcher 只
 * 转发清单内的 command。修改清单请改 app/contracts/map_commands.py 后运行
 * `python -m app.contracts.map_commands` 再生成。
 */
"""


def render() -> str:
    lines = [_HEADER]
    lines.append(f"export const MAP_COMMAND_MANIFEST_VERSION = {MAP_COMMAND_MANIFEST_VERSION};\n")
    lines.append("export const MAP_COMMAND_MANIFEST = [")
    lines.extend(f"  '{name}'," for name in MAP_COMMANDS)
    lines.append("] as const;\n")
    lines.append("export type MapCommandManifestName = (typeof MAP_COMMAND_MANIFEST)[number];")
    return "\n".join(lines) + "\n"


def generate() -> Path:
    OUTPUT.write_text(render(), encoding="utf-8")
    return OUTPUT


def check_drift() -> dict[str, Any]:
    if not OUTPUT.exists():
        return {"drifted": True, "reason": "missing"}
    if OUTPUT.read_text(encoding="utf-8") == render():
        return {"drifted": False, "reason": None}
    return {"drifted": True, "reason": "committed file differs from regeneration"}


if __name__ == "__main__":
    print(f"wrote {generate()}")  # noqa: T201 — CLI 生成器输出
