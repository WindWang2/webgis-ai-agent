"""ads-v1 DS2 retrieval eval gate (ADR-0172): Recall@5 / MRR ratchet.

Loads the labelled bilingual eval set (tests/data/ads2_retrieval_eval.json,
generated by scripts/ads_gen_retrieval_eval.py from the registry cards) and
asserts the DS2 acceptance thresholds. Provisional in the first round — DS8
re-fits ranking weights against this same set and raises the bar.

Thresholds (task book §6 DS2): Recall@5 ≥ 0.80 · MRR ≥ 0.55.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.services.data_fabric.retrieval import get_retrieval_service

EVAL = Path(__file__).resolve().parent / "ads2_retrieval_eval.json"


@pytest.fixture(scope="module")
def metrics() -> dict:
    data = json.loads(EVAL.read_text(encoding="utf-8"))
    svc = get_retrieval_service()
    hits5 = 0
    rr = 0.0
    for s in data["samples"]:
        resp = svc.retrieve(s["query"], top_k=5)
        rank = next(
            (i + 1 for i, h in enumerate(resp.hits) if h.card_id == s["expected"]),
            None,
        )
        if rank:
            hits5 += 1
            rr += 1.0 / rank
    n = len(data["samples"])
    return {"n": n, "recall_at_5": hits5 / n, "mrr": rr / n}


def test_eval_set_is_big_enough():
    data = json.loads(EVAL.read_text(encoding="utf-8"))
    assert data["n"] >= 200, f"eval set shrunk to {data['n']} (need ≥200)"


def test_recall_at_5_threshold(metrics):
    print(f"\n[ads2-eval] n={metrics['n']} Recall@5={metrics['recall_at_5']:.4f} MRR={metrics['mrr']:.4f}")
    assert metrics["recall_at_5"] >= 0.80, f"Recall@5 {metrics['recall_at_5']:.4f} < 0.80"


def test_mrr_threshold(metrics):
    assert metrics["mrr"] >= 0.55, f"MRR {metrics['mrr']:.4f} < 0.55"
